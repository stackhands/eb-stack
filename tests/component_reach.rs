#[test]
fn cargo_and_npm_purls_do_not_match_the_curl_recipe() {
    let dir = tempfile::tempdir().expect("temp");
    let root = dir.path();
    std::fs::write(
        root.join("cURL.eb"),
        "name = 'cURL'\nversion = '8.17.0'\ntoolchain = {'name': 'GCCcore', 'version': '15.2.0'}\n",
    )
    .unwrap();
    std::fs::write(
        root.join("cargo-curl.eb"),
        "name = 'cargo-curl'\nversion = '0.1'\neasyblock = 'Cargo'\ntoolchain = {'name': 'GCCcore', 'version': '15.2.0'}\ncrates = [('curl', '8.17.0')]\n",
    )
    .unwrap();
    std::fs::write(
        root.join("npm-bundle.eb"),
        "name = 'npm-bundle'\nversion = '1'\neasyblock = 'Bundle'\nexts_defaultclass = 'NpmPackage'\ntoolchain = {'name': 'GCCcore', 'version': '15.2.0'}\nexts_list = [('curl', '8.17.0', {})]\n",
    )
    .unwrap();
    let cargo = reach_purl(root, "pkg:cargo/curl@8.17.0");
    let files: Vec<_> = cargo["carriers"]
        .as_array()
        .unwrap()
        .iter()
        .map(|row| row["easyconfig"].as_str().unwrap().to_string())
        .collect();
    assert!(
        !files.iter().any(|file| file == "cURL.eb"),
        "cargo purl matched the cURL recipe: {files:?}"
    );
    assert!(
        files.iter().any(|file| file == "cargo-curl.eb"),
        "cargo purl missed the crate: {files:?}"
    );
    let npm = reach_purl(root, "pkg:npm/curl@8.17.0");
    let files: Vec<_> = npm["carriers"]
        .as_array()
        .unwrap()
        .iter()
        .map(|row| row["easyconfig"].as_str().unwrap().to_string())
        .collect();
    assert!(
        !files.iter().any(|file| file == "cURL.eb"),
        "npm purl matched the cURL recipe: {files:?}"
    );
    assert!(
        files.iter().any(|file| file == "npm-bundle.eb"),
        "npm purl missed the extension: {files:?}"
    );
    let output = Command::new(env!("CARGO_BIN_EXE_eb-stack"))
        .env_remove("EASYBUILD_FILTER_DEPS")
        .args([
            "component-reach",
            "--purl",
            "pkg:gem/curl@8.17.0",
            "--generation",
            "2026.1",
            "--easyconfigs",
        ])
        .arg(root)
        .args(["--generated-at", "2026-10-24T00:00:00Z", "--out-dir"])
        .arg(root.join("gem-out"))
        .output()
        .expect("run");
    assert_eq!(output.status.code(), Some(2), "{output:?}");
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("no carrier model"),
        "stderr should name the missing model: {stderr}"
    );
}

#[test]
fn recorded_slice_matches_the_pinned_develop_commit() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/component_reach_recorded");
    let checks = [
        (
            "LICENSE",
            "8177f97513213526df2cf6184d8ff986c675afb514d4e68a404010521b880643",
        ),
        (
            "easybuild/easyconfigs/c/cURL/cURL-8.17.0-GCCcore-15.2.0.eb",
            "e9eea495bfa797007d602363fe99bae6f5feb7aad968c8e4cec1b1400c6a3c3d",
        ),
        (
            "easybuild/easyconfigs/g/git/git-2.52.0-GCCcore-15.2.0.eb",
            "0ceae55b53436866fab93b7c705126f0168b1d915de8164cf74bfeed9868344c",
        ),
    ];
    for (rel, want) in checks {
        let path = root.join(rel);
        let output = Command::new("sha256sum")
            .arg(&path)
            .output()
            .unwrap_or_else(|error| panic!("sha256sum {rel}: {error}"));
        assert!(output.status.success(), "{rel}");
        let got = String::from_utf8(output.stdout).unwrap();
        let got = got.split_whitespace().next().unwrap_or("");
        assert_eq!(got, want, "{rel}");
    }
    let licence = std::fs::read_to_string(root.join("LICENSE")).unwrap();
    assert!(licence.contains("GNU GENERAL PUBLIC LICENSE"));
}

fn reach_purl(root: &Path, purl: &str) -> serde_json::Value {
    let out = root.join(purl.replace([':', '/', '@'], "_"));
    let output = Command::new(env!("CARGO_BIN_EXE_eb-stack"))
        .env_remove("EASYBUILD_FILTER_DEPS")
        .args([
            "component-reach",
            "--purl",
            purl,
            "--generation",
            "2026.1",
            "--easyconfigs",
        ])
        .arg(root)
        .args(["--generated-at", "2026-10-24T00:00:00Z", "--out-dir"])
        .arg(&out)
        .output()
        .expect("run");
    assert!(
        output.status.success(),
        "{purl}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    serde_json::from_str(&std::fs::read_to_string(out.join("component-reach.json")).unwrap())
        .unwrap()
}

/// A purl type with no carrier model is a usage error and writes nothing.
#[test]
fn an_unsupported_purl_type_creates_no_output_directory() {
    let tmp = tempfile::tempdir().expect("temp");
    let out_dir = tmp.path().join("reach");
    let output = Command::new(env!("CARGO_BIN_EXE_eb-stack"))
        .args([
            "component-reach",
            "--purl",
            "pkg:deb/debian/curl@8.17.0",
            "--generation",
            "2026.1",
            "--easyconfigs",
            "tests/component_reach_fixtures",
            "--out-dir",
            out_dir.to_str().unwrap(),
        ])
        .output()
        .expect("run");
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert_eq!(output.status.code(), Some(2), "{stderr}");
    assert!(
        stderr.contains("purl type deb has no carrier model"),
        "{stderr}"
    );
    assert!(!out_dir.exists(), "left {}", out_dir.display());
}

/// Run `component-reach` for curl 8 on a tree of `(file, text)` recipes.
fn reach_curl(files: &[(&str, &str)]) -> serde_json::Value {
    let dir = tempfile::tempdir().expect("temp");
    let tree = dir.path().join("easyconfigs");
    std::fs::create_dir_all(&tree).expect("tree");
    for (file, text) in files {
        std::fs::write(tree.join(file), text).expect("recipe");
    }
    let out = dir.path().join("out");
    let output = Command::new(env!("CARGO_BIN_EXE_eb-stack"))
        .env_remove("EASYBUILD_FILTER_DEPS")
        .args([
            "component-reach",
            "--component",
            "curl",
            "--version",
            ">=8,<9",
            "--generation",
            "2026.1",
            "--easyconfigs",
        ])
        .arg(&tree)
        .args(["--generated-at", "2026-10-22T12:00:00Z", "--out-dir"])
        .arg(&out)
        .output()
        .expect("run");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    serde_json::from_str(&std::fs::read_to_string(out.join("component-reach.json")).unwrap())
        .unwrap()
}

const CURL: (&str, &str) = (
    "cURL-8.17.0-GCCcore-15.2.0.eb",
    "name = 'cURL'\nversion = '8.17.0'\ntoolchain = {'name': 'GCCcore', 'version': '15.2.0'}\n",
);
const R_ON_GFBF: (&str, &str) = (
    "R-4.6.1-gfbf-2026.1.eb",
    "name = 'R'\nversion = '4.6.1'\ntoolchain = {'name': 'gfbf', 'version': '2026.1'}\ndependencies = [('cURL', '8.17.0')]\n",
);
const NETCDF_ON_GOMPI: (&str, &str) = (
    "netCDF-4.10.0-gompi-2026.1.eb",
    "name = 'netCDF'\nversion = '4.10.0'\ntoolchain = {'name': 'gompi', 'version': '2026.1'}\ndependencies = [('cURL', '8.17.0')]\n",
);
const GDAL_ON_FOSS: (&str, &str) = (
    "GDAL-3.13.0-foss-2026.1.eb",
    "name = 'GDAL'\nversion = '3.13.0'\ntoolchain = {'name': 'foss', 'version': '2026.1'}\ndependencies = [('cURL', '8.17.0')]\n",
);

fn closure_dependents(json: &serde_json::Value) -> Vec<String> {
    let mut dependents: Vec<String> = json["closure_rows"]
        .as_array()
        .expect("closure_rows")
        .iter()
        .map(|row| {
            format!(
                "{} {}",
                row["dependent"].as_str().unwrap(),
                row["edge_kind"].as_str().unwrap()
            )
        })
        .collect();
    dependents.sort();
    dependents
}

/// gfbf and gompi have no built-in hierarchy; it is derived from their
/// definition recipes, which are SYSTEM recipes outside the generation.
#[test]
fn dependents_on_every_toolchain_of_the_generation_are_in_the_closure() {
    let json = reach_curl(&[
        CURL,
        R_ON_GFBF,
        NETCDF_ON_GOMPI,
        GDAL_ON_FOSS,
        (
            "gfbf-2026.1.eb",
            "name = 'gfbf'\nversion = '2026.1'\ntoolchain = SYSTEM\ndependencies = [('GCC', '15.2.0'), ('FlexiBLAS', '3.5.0', '', ('GCC', '15.2.0'))]\n",
        ),
        (
            "gompi-2026.1.eb",
            "name = 'gompi'\nversion = '2026.1'\ntoolchain = SYSTEM\ndependencies = [('GCC', '15.2.0'), ('OpenMPI', '5.0.10', '', ('GCC', '15.2.0'))]\n",
        ),
    ]);
    assert_eq!(
        closure_dependents(&json),
        [
            "GDAL/3.13.0-foss-2026.1 runtime",
            "R/4.6.1-gfbf-2026.1 runtime",
            "cURL/8.17.0-GCCcore-15.2.0 changed",
            "netCDF/4.10.0-gompi-2026.1 runtime",
        ],
        "{json:#}"
    );
}

/// Without the gfbf and gompi definitions their recipes cannot resolve cURL.
/// The closure then lacks them, and the report has to say so.
#[test]
fn a_dependency_the_closure_cannot_resolve_is_listed() {
    let json = reach_curl(&[CURL, R_ON_GFBF, NETCDF_ON_GOMPI, GDAL_ON_FOSS]);
    let unresolved: Vec<&str> = json["closure_unresolved"]
        .as_array()
        .expect("closure_unresolved")
        .iter()
        .filter_map(|requirement| requirement.as_str())
        .collect();
    for requirement in [
        "R/4.6.1-gfbf-2026.1 needs cURL ==8.17.0",
        "netCDF/4.10.0-gompi-2026.1 needs cURL ==8.17.0",
    ] {
        assert!(
            unresolved.contains(&requirement),
            "{requirement} not in {unresolved:#?}"
        );
    }
}
